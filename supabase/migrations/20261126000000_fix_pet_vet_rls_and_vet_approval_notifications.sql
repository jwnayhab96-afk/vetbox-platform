-- Break the pet_vet_links <-> veterinarian_profiles RLS recursion.
-- Helpers run as the database owner and return only the boolean needed by the policy.
CREATE OR REPLACE FUNCTION public.current_user_owns_pet(target_pet_id UUID)
RETURNS BOOLEAN
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
SET row_security = off
AS $$
    SELECT EXISTS (
        SELECT 1
        FROM public.pets p
        WHERE p.id = target_pet_id
          AND p.owner_id = auth.uid()
    );
$$;

CREATE OR REPLACE FUNCTION public.is_verified_veterinarian(target_vet_id UUID)
RETURNS BOOLEAN
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
SET row_security = off
AS $$
    SELECT EXISTS (
        SELECT 1
        FROM public.veterinarian_profiles vp
        WHERE vp.id = target_vet_id
          AND vp.verification_status = 'verified'::public.vet_verification_status
    );
$$;

REVOKE ALL ON FUNCTION public.current_user_owns_pet(UUID) FROM PUBLIC, anon;
REVOKE ALL ON FUNCTION public.is_verified_veterinarian(UUID) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.current_user_owns_pet(UUID) TO authenticated;
GRANT EXECUTE ON FUNCTION public.is_verified_veterinarian(UUID) TO authenticated;

-- requested_by is fixed to the owner at creation; the update trigger prevents changing it.
DROP POLICY IF EXISTS "Links viewable by involved owner or vet" ON public.pet_vet_links;
CREATE POLICY "Links viewable by involved owner or vet"
ON public.pet_vet_links FOR SELECT TO authenticated
USING (
    requested_by = (SELECT auth.uid())
    OR vet_id = (SELECT auth.uid())
    OR public.current_user_owns_pet(pet_id)
    OR public.current_user_role() = 'admin'
);

DROP POLICY IF EXISTS "Owners can create link requests" ON public.pet_vet_links;
CREATE POLICY "Owners can create link requests"
ON public.pet_vet_links FOR INSERT TO authenticated
WITH CHECK (
    requested_by = (SELECT auth.uid())
    AND public.current_user_owns_pet(pet_id)
    AND public.is_verified_veterinarian(vet_id)
);

DROP POLICY IF EXISTS "Involved parties can update connection status" ON public.pet_vet_links;
CREATE POLICY "Involved parties can update connection status"
ON public.pet_vet_links FOR UPDATE TO authenticated
USING (
    requested_by = (SELECT auth.uid())
    OR vet_id = (SELECT auth.uid())
    OR public.current_user_owns_pet(pet_id)
    OR public.current_user_role() = 'admin'
)
WITH CHECK (
    requested_by = (SELECT auth.uid())
    OR vet_id = (SELECT auth.uid())
    OR public.current_user_owns_pet(pet_id)
    OR public.current_user_role() = 'admin'
);

GRANT SELECT, INSERT, UPDATE ON TABLE public.pet_vet_links TO authenticated;

-- Notifications are generated by trusted database functions, not by client inserts.
DROP POLICY IF EXISTS "Users can view and manage their own notifications" ON public.notifications;
DROP POLICY IF EXISTS "Users read their own notifications" ON public.notifications;
DROP POLICY IF EXISTS "Users mark their own notifications read" ON public.notifications;
CREATE POLICY "Users read their own notifications"
ON public.notifications FOR SELECT TO authenticated
USING (user_id = (SELECT auth.uid()));
CREATE POLICY "Users mark their own notifications read"
ON public.notifications FOR UPDATE TO authenticated
USING (user_id = (SELECT auth.uid()))
WITH CHECK (user_id = (SELECT auth.uid()));

REVOKE ALL ON TABLE public.notifications FROM anon, authenticated;
GRANT SELECT ON TABLE public.notifications TO authenticated;
GRANT UPDATE (is_read) ON TABLE public.notifications TO authenticated;
CREATE INDEX IF NOT EXISTS idx_notifications_user_created
ON public.notifications (user_id, created_at DESC);

-- Notify the veterinarian once when an administrator changes their status to verified.
CREATE OR REPLACE FUNCTION public.review_veterinarian(
    target_vet_id UUID,
    new_status public.vet_verification_status,
    reason TEXT DEFAULT NULL
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    previous_status public.vet_verification_status;
BEGIN
    IF public.current_user_role() IS DISTINCT FROM 'admin'::public.user_role THEN
        RAISE EXCEPTION 'Administrator role required';
    END IF;

    SELECT vp.verification_status INTO previous_status
    FROM public.veterinarian_profiles vp
    WHERE vp.id = target_vet_id;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Veterinarian profile not found';
    END IF;

    UPDATE public.veterinarian_profiles
    SET verification_status = new_status,
        verified_at = CASE WHEN new_status = 'verified' THEN now() ELSE NULL END,
        verified_by = auth.uid(),
        rejection_reason = CASE WHEN new_status = 'rejected' THEN reason ELSE NULL END,
        updated_at = now()
    WHERE id = target_vet_id;

    IF new_status = 'verified' AND previous_status IS DISTINCT FROM 'verified'::public.vet_verification_status THEN
        INSERT INTO public.notifications (user_id, title, message, type, link)
        VALUES (
            target_vet_id,
            'تم اعتماد ترخيصك البيطري',
            'راجعت الإدارة بياناتك واعتمدت ترخيصك. أصبح حسابك المهني موثقًا ويمكنك استخدام خدمات الأطباء المعتمدين.',
            'system',
            '/veterinarian/verification'
        );
    END IF;

    INSERT INTO public.audit_logs (user_id, action, resource_type, resource_id, metadata)
    VALUES (
        auth.uid(),
        'VETERINARIAN_REVIEWED',
        'veterinarian_profile',
        target_vet_id::TEXT,
        jsonb_build_object('status', new_status, 'reason', reason)
    );
END;
$$;

REVOKE ALL ON FUNCTION public.review_veterinarian(UUID, public.vet_verification_status, TEXT) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.review_veterinarian(UUID, public.vet_verification_status, TEXT) TO authenticated;
